#!/usr/bin/env python3
"""conventions-scan(파일 전체 검사, 기계적 고치기) 회귀 표. 실행: python3 -I test-conventions-scan.py  (exit 0 = 통과)

임시 git 저장소에 픽스처를 만들고 스크립트를 하위 프로세스(CLI)와 모듈(가드 대체 시험)로 부른다. 모델을 부르지 않는다.
"""
import hashlib
import importlib.util
import io
import json
import os
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SCRIPT = os.path.join(os.path.dirname(HERE), "scripts", "conventions-scan.py")
HOOKS = os.path.join(os.path.dirname(HERE), "hooks")
T = tempfile.mkdtemp(prefix="conv-scan-")
REPO = os.path.join(T, "repo")
res = []


def check(name, ok):
    res.append((name, bool(ok)))


def put(rel, content, mode="w"):
    p = os.path.join(REPO, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, mode, **({} if "b" in mode else {"encoding": "utf-8"})) as f:
        f.write(content)
    return p


def read(rel, binary=False):
    with open(os.path.join(REPO, rel), "rb" if binary else "r", **({} if binary else {"encoding": "utf-8", "newline": ""})) as f:
        return f.read()


def digest():
    h = hashlib.sha256()
    for d, dirs, files in sorted(os.walk(REPO)):
        dirs[:] = sorted(x for x in dirs if x != ".git")
        for f in sorted(files):
            h.update(f.encode() + open(os.path.join(d, f), "rb").read())
    return h.hexdigest()


def cli(*args):
    p = subprocess.run([sys.executable, "-I", SCRIPT] + list(args) + ["--root", REPO], capture_output=True, text=True, timeout=120, cwd=REPO)
    return p.returncode, p.stdout, p.stderr


def git(*args):
    subprocess.run(["git", "-C", REPO] + list(args), check=True, capture_output=True)


def setup():
    os.makedirs(REPO)
    git("-c", "init.defaultBranch=main", "init", "-q")
    put(".claude/conventions.json", json.dumps({"exclude": ["legacy/**"]}))
    put(".gitignore", "ignored/\n")
    put("src/a.luau", "\n".join([
        "-- Clamp the index so reads stay in range (H-973).",          # 1 history
        "-- keep a \u2192 b and c \u2014 d, e\u00b7f, wait\u2026",              # 2 symbols
        'local s = "x \u2192 y"  -- tail \u2192 here',                    # 3 string keeps, comment fixed
        "-- a\u00a0b and c\u200bd",                                     # 4 invisible in comment
        'local z = "p\u200bq"',                                        # 5 invisible in code -> judgment
        "-- the dot is \\u00b7 here",                                  # 6 escape -> judgment
        "-- done \u2705",                                               # 7 emoji -> judgment
        "-- `a \u2192 b` stays quoted",                                 # 8 inline code -> judgment
        "local n = 1",
        ""]))
    put("src/b.ts", 'const s = "x \u2192 y"; /* a\u00b7b */ // c \u2014 d\n')
    put("src/c.html", "<p>x</p>\n<!-- a -\u2192 b -->\n")
    put("src/crlf.py", "x = 1  # a \u2192 b\r\ny = 2\r\n".encode("utf-8"), "wb")
    put("legacy/old.luau", "-- H-973\n")
    put("ignored/i.luau", "-- H-973\n")
    put("gen/g.luau", "-- generated by tool, do not edit\n-- H-973\n")
    put("fixtures/f.luau", "-- H-973\n")
    put("README.md", "# X\nDecided 2026-11-10 \u2192 ok\n")
    put("skills/s/SKILL.md", "\n".join([
        "---", "name: s", "description: made 2026-11-10", "---",
        "# S",
        "Decided 2026-11-10.",                       # 6 history
        "Use\u00a0tabs \u2192 here.",                 # 7 invisible in prose (fixed), arrow not a doc category
        "Run `a\u00a0b` now.",                        # 8 invisible in inline code -> judgment
        "```", "x\u200by", "```",                    # 10 invisible in fence -> judgment
        ""]))
    put("clean/ok.luau", "-- Walk in reverse so removals do not shift indices.\nlocal a = 1\n")
    git("add", "-A")
    put("src/untracked.luau", "-- Q188 note\n")  # 추적 안 됨, 무시도 안 됨: 본다


setup()

# ---- 검사 ----
rc, out, err = cli("scan")
check("scan exits 1 with findings", rc == 1)
for want in ["src/a.luau:1: history marker", "src/a.luau:2: non-keyboard symbol", "src/a.luau:3: non-keyboard symbol",
             "src/a.luau:4: invisible character", "src/a.luau:5: invisible character", "src/a.luau:6: escaped character",
             "src/a.luau:7: non-keyboard symbol", "src/b.ts:1: non-keyboard symbol", "skills/s/SKILL.md:6: history marker",
             "skills/s/SKILL.md:7: invisible character", "skills/s/SKILL.md:10: invisible character", "src/untracked.luau:1: history marker"]:
    check(f"scan finds {want}", want in out)
check("scan line format path:line: category: detail", "src/a.luau:1: history marker: H-973" in out)
check("excluded, ignored, generated, fixtures, frontmatter, non-model md are skipped",
      all(x not in out for x in ["legacy/", "ignored/", "gen/", "fixtures/", "README.md", "SKILL.md:3"]))
check("doc symbols are not a doc category", "SKILL.md:7: non-keyboard symbol" not in out)
check("summary per category and per file", "findings:" in out and "history marker:" in out and "files with findings:" in out and "src/a.luau" in out.split("files with findings:")[1])
check("summary shows the fixable estimate", "fixable by --fix:" in out and "needs judgment:" in out)

rc, out, err = cli("scan", "--json")
data = json.loads(out)
cats = {(f["path"], f["line"], f["category"]) for f in data["findings"]}
check("--json findings and summary", rc == 1 and ("src/a.luau", 1, "history marker") in cats and data["summary"]["by_category"]["history marker"] >= 2
      and data["summary"]["skipped"].get("excluded") == 2 and data["summary"]["skipped"].get("generated") == 1)
rc, out, err = cli("scan", "--json", "--category", "symbol")
check("--category limits findings", {f["category"] for f in json.loads(out)["findings"]} == {"non-keyboard symbol"})
rc, out, err = cli("scan", "--category", "nope")
check("unknown category -> exit 2", rc == 2 and "unknown category" in err)
rc, out, err = cli("scan", os.path.join(REPO, "clean"))
check("clean path -> exit 0", rc == 0 and "findings: 0" in out)
rc, out, err = cli("scan", os.path.join(REPO, "src", "b.ts"))
check("single file path", rc == 1 and "src/b.ts:1" in out and "src/a.luau" not in out)
check("--dry-run without --fix is an error", cli("scan", "--dry-run")[0] == 2)

# ---- 고치기: dry-run 은 아무것도 쓰지 않는다 ----
before = digest()
rc, out, err = cli("fix", "--dry-run")
check("dry-run writes nothing", digest() == before)
check("dry-run prints a unified diff", "--- a/src/a.luau" in out and "+++ b/src/a.luau" in out and "+-- keep a -> b and c - d, e, f, wait..." in out)
check("dry-run shows invisible chars as code points", "<U+00A0>" in out and "# invisible characters are shown" in out)

# ---- 고치기 ----
a_before = read("src/a.luau").split("\n")
rc, out, err = cli("fix")
a_after = read("src/a.luau").split("\n")
check("fix exits 1 while judgment items remain", rc == 1 and "needs judgment:" in out)
check("comment symbols replaced", a_after[1] == "-- keep a -> b and c - d, e, f, wait...")
check("string literal untouched, trailing comment fixed", a_after[2] == 'local s = "x \u2192 y"  -- tail -> here')
check("invisible chars in comment: NBSP -> space, ZWSP removed", a_after[3] == "-- a b and cd")
check("judgment lines unchanged (history, code invisible, escape, emoji, inline code)",
      [a_after[i] for i in (0, 4, 5, 6, 7, 8)] == [a_before[i] for i in (0, 4, 5, 6, 7, 8)])
check("needs judgment lists what is left",
      all(x in out for x in ["src/a.luau:1: history marker", "src/a.luau:5: invisible character", "src/a.luau:6: escaped character",
                             "src/a.luau:7: non-keyboard symbol", "src/a.luau:8: non-keyboard symbol"])
      and "src/a.luau:2:" not in out.split("needs judgment:")[1])
check("ts: block and line comment fixed, string kept", read("src/b.ts") == 'const s = "x \u2192 y"; /* a, b */ // c - d\n')
check("CRLF line endings kept", read("src/crlf.py", True) == b"x = 1  # a -> b\r\ny = 2\r\n")
skill = read("skills/s/SKILL.md").split("\n")
check("doc prose NBSP fixed, arrow kept (not a doc category)", skill[6] == "Use tabs \u2192 here.")
check("doc inline code, fence, frontmatter, history untouched",
      skill[7] == "Run `a\u00a0b` now." and skill[9] == "x\u200by" and skill[2] == "description: made 2026-11-10" and skill[5] == "Decided 2026-11-10.")
check("excluded and ignored files untouched", read("legacy/old.luau") == "-- H-973\n" and read("ignored/i.luau") == "-- H-973\n")
check("html: fix that would close the comment early is rejected by the guard",
      read("src/c.html") == "<p>x</p>\n<!-- a -\u2192 b -->\n" and "rejected" in out and "src/c.html" in out.split("token guard:")[1].split("\n")[0])
check("fix reports the guard", "token guard:" in out)
rc2, out2, _ = cli("fix")
check("second fix run changes nothing more", "fixed: 0 findings" in out2 or "fixed: 0" in out2)

# ---- 모듈 단위: 대체 규칙 ----
sys.path.insert(0, HOOKS)
spec = importlib.util.spec_from_file_location("conv_scan", SCRIPT)
cs = importlib.util.module_from_spec(spec)
spec.loader.exec_module(cs)
from collections import Counter  # noqa: E402

SYM = ("non-keyboard symbol", "invisible character")
cases = [
    (" a \u2014 b", " a - b"), (" a\u2014b", " a - b"), (" \u2014 lead", " - lead"), (" ends \u2014", " ends -"),
    (" 1\u20133 pages", " 1-3 pages"), (" a \u2013 b", " a - b"), (" x \u2212 1", " x - 1"), (" 5\u22122", " 5-2"),
    (" a\u00b7b", " a, b"), (" a \u00b7 b", " a, b"), (" 0.734\u00b70.742", " 0.734, 0.742"), (" \u00b7 item", " - item"),
    (" \u3131\u00b7\u3134", " \u3131, \u3134"), (' the "\u00b7" mark', ' the "\u00b7" mark'),
    (" wait\u2026", " wait..."), (" a\u2192b \u2190 c \u2194 d \u21d2 e", " a->b <- c <-> d => e"),
    (" \u201cq\u201d \u2018r\u2019", " \"q\" 'r'"), (" see \u00a7 4.2", " see 4.2"), (" \u00a73", " 3"),
    (" \u2460first \u2461 second", " 1) first 2) second"), (" 2\u00d73 \u2265 1 \u2264 9 \u2260 0", " 2x3 >= 1 <= 9 != 0"),
    (" \uff08x\uff09\u3000y", " (x) y"), (" \u2022 item", " - item"),
    (" a\u00a0b", " a b"), (" a\u200bb\u200e\u2066c\u00ad", " abc"),
    (" box \u2500\u2500 \u2248 \u2229 \u2705 \u26a0", " box \u2500\u2500 \u2248 \u2229 \u2705 \u26a0"),
]
for src, want in cases:
    got = cs.fix_segment(src, SYM, [], Counter())
    check(f"fix_segment {ascii(src)} -> {ascii(want)}", got == want)
check("ZWJ inside an emoji sequence stays", cs.fix_segment(" \U0001F468\u200d\U0001F469", SYM, ["emoji"], Counter()) == " \U0001F468\u200d\U0001F469")
check("allow_chars literal is kept", cs.fix_segment(" a \u2192 b", SYM, ["\u2192"], Counter()) == " a \u2192 b")
check("only invisible category leaves symbols", cs.fix_segment(" a \u2192\u00a0b", ("invisible character",), [], Counter()) == " a \u2192 b")
check("directive comment symbols are left (hook skips them)",
      cs.plan_code_fix("x = 1  # noqa: E402 \u2192 y\n", "py", SYM, [], Counter()) == "x = 1  # noqa: E402 \u2192 y\n")

# ---- 렉서 위치: 조각과 위치가 맞는다 ----
for fam, txt in [("lua", "local a = 1 -- x\n--[[ b\nc ]] d\n"), ("c", 'f("//") /* a */ g // h\n/*\n x */\n'), ("py", "s = '#'  # c\n"),
                 ("html", "<p>\n<!-- a\nb --> c\n"), ("rust", "fn f<'a>() {} // x\n")]:
    rows = cs.lex(txt, fam)
    lines = txt.split("\n")
    check(f"lexer spans match fragments ({fam})", all(lines[i][a:b] == c for i, r in enumerate(rows) for (a, b), c in zip(r["s"], r["c"]))
          and all(len(r["s"]) == len(r["c"]) for r in rows))

# ---- 토큰 가드 ----
check("guard: comment-only change passes", cs.guard_ok("x = 1 # a\n", "x = 1 # b c\n", "comment", "py"))
check("guard: code change fails", not cs.guard_ok("x = 1 # a\n", "x = 2 # a\n", "comment", "py"))
check("guard: string change fails", not cs.guard_ok('s = "\u2192" # a\n', 's = "->" # a\n', "comment", "py"))
check("guard: comment closed early fails", not cs.guard_ok("/* a */ x\n", "/* a */ b */ x\n", "comment", "c"))
check("guard: doc inline code change fails", not cs.guard_ok("Run `a\u00a0b`.\n", "Run `a b`.\n", "doc", None))
check("guard: doc fence change fails", not cs.guard_ok("```\nx\u200by\n```\n", "```\nxy\n```\n", "doc", None))
check("guard: doc prose change passes", cs.guard_ok("Use\u00a0tabs.\n", "Use tabs.\n", "doc", None))


def run_mod(*args):
    buf = io.StringIO()
    rc = cs.run(cs.parse(list(args) + ["--root", REPO]), out=buf)
    return rc, buf.getvalue()


# 일부러 망가뜨린 고치기: 주석만이 아니라 파일 전체에서 화살표를 바꾼다(문자열 리터럴까지)
put("broken/s.luau", 'local s = "a \u2192 b"  -- c \u2192 d\n')
git("add", "-A")
orig_plan = cs.plan_fix
cs.plan_fix = lambda text, rel, cats, allow, skip=(): (text.replace("\u2192", "->"), Counter({("\u2192", "->"): text.count("\u2192")}))
rc, out = run_mod("fix", os.path.join(REPO, "broken"))
check("guard catches a broken fixer (string literal changed) and leaves the file", "rejected" in out and "broken/s.luau" in out
      and read("broken/s.luau") == 'local s = "a \u2192 b"  -- c \u2192 d\n')
cs.plan_fix = orig_plan

# 다시 읽은 결과가 가드를 못 넘으면 원본 바이트로 되돌린다
orig_guard = cs.guard_ok
calls = [0]


def flaky(*a):
    calls[0] += 1
    return calls[0] == 1


cs.guard_ok = flaky
rc, out = run_mod("fix", os.path.join(REPO, "broken"))
check("guard failure after write restores the original bytes", read("broken/s.luau") == 'local s = "a \u2192 b"  -- c \u2192 d\n'
      and "rejected" in out and calls[0] == 2 and not os.path.exists(os.path.join(REPO, "broken", "s.luau.conventions-fix.tmp")))
cs.guard_ok = orig_guard
rc, out = run_mod("fix", os.path.join(REPO, "broken"))
check("real fixer on the same file changes only the comment", read("broken/s.luau") == 'local s = "a \u2192 b"  -- c -> d\n' and rc == 0)

# ---- 사본은 고치지 않는다(정본을 고치고 sync-copies --apply) ----
put("lib/canon.py", "# a \u2192 b\n")
put("plug/copy.py", '"""x.\n@copy-of: lib/canon.py\n"""\n# a \u2192 b\n')
put("plug/region.py", "# keep \u2192 here\n# @start-replace: lib/canon.py#R\n# c \u2192 d\n# @end-replace\n")
git("add", "-A")
rc, out = run_mod("fix", os.path.join(REPO, "lib"), os.path.join(REPO, "plug"))
check("whole-file copy is left, canon is fixed", read("plug/copy.py").endswith("# a \u2192 b\n") and read("lib/canon.py") == "# a -> b\n")
check("region copy lines are left, lines outside the region are fixed",
      read("plug/region.py") == "# keep -> here\n# @start-replace: lib/canon.py#R\n# c \u2192 d\n# @end-replace\n")
check("copies are reported with the sync hint", "copies left unfixed: plug/copy.py, plug/region.py" in out and "sync-copies.py --apply" in out)

# ---- 단계 라벨: 한국어 주석 파일의 영어 라벨은 language 가 아니다 ----
ko = "".join(f"-- 이 값은 플레이어가 들어올 때만 갱신한다 {i}\n" for i in range(12))
put("lbl/a.luau", ko + "local function f()\n\tlocal parent = 1\n\t-- Detach previous parent first\n\tparent = nil\nend\n")
put("lbl/b.luau", ko + "local function f()\n\tlocal parent = 1\n\t-- Clamp the index so reads stay in range\n\tparent = nil\nend\n")
git("add", "-A")
rc, out, _ = cli("scan", os.path.join(REPO, "lbl", "a.luau"))
check("scan: English step label in a Korean file is not a language finding", rc == 0 and "language mismatch" not in out)
rc, out, _ = cli("scan", os.path.join(REPO, "lbl", "b.luau"))
check("scan: an English reason sentence still is", rc == 1 and "lbl/b.luau:15: language mismatch" in out)

# ---- layout 하위 명령 ----
flat = "--!strict\nlocal M = {}\n\n-- Hidden.\nfunction M.flat(x)\n" + "".join(f"\tlocal v{i} = x + {i}\n" for i in range(20)) + "end\n"
pair = ("--- Reads a pair.\nfunction M.pair(x)\n\tlocal ok, err = pcall(x)\n\tlocal a, b = 1, 2\n\n"
        "\t-- Return the result\n\treturn ok, err, a, b\nend\n\nfunction M.__tostring()\n\treturn \"M\"\nend\n\nreturn M\n")
put("lay/m.luau", flat + "\n" + pair)
put("lay/ok.luau", "--- Adds one.\nlocal function inc(x)\n\treturn x + 1\nend\n\nreturn inc\n")
put("lay/notes.md", "# not code\n")
git("add", "-A")
before = digest()
rc, out, _ = cli("layout", os.path.join(REPO, "lay"))
check("layout: per-function line with numbers and categories",
      "lay/m.luau:5-26: M.flat (public): 20 lines, 0 blank, 1 paragraphs, longest run 20" in out and "[layout, doc summary]" in out)
check("layout: multi-return is not a multi-declaration, a, b = 1, 2 is",
      "M.pair (public): 4 lines, 1 blank, 2 paragraphs, longest run 2, labels 1, interleaved 0, multi-decl 1" in out)
check("layout: metamethod has no doc summary", "M.__tostring" in out and "__tostring (public): 1 lines, 0 blank, 1 paragraphs, longest run 1, labels 0, interleaved 0, multi-decl 0, one-letter 0, doc none\n" in out)
check("layout: summary and exit code 1 with findings", rc == 1 and "functions with 15+ lines: 1, read as one block: 1" in out
      and "public functions with a doc comment callers can see: 1/2" in out and "notes.md" not in out)
check("layout: writes nothing", digest() == before)
rc, out, _ = cli("layout", os.path.join(REPO, "lay", "ok.luau"))
check("layout: clean file exits 0", rc == 0 and "findings: none" in out)
rc, out, _ = cli("layout", os.path.join(REPO, "lay"), "--json")
data = json.loads(out)
check("layout: --json has functions and summary", rc == 1 and data["summary"]["functions"] == 4
      and any(f["name"] == "M.flat" and "layout" in f["findings"] for f in data["functions"]))
put(".claude/conventions.json", '{"layout": {"min_lines": 30}}')
rc, out, _ = cli("layout", os.path.join(REPO, "lay", "m.luau"), "--summary")
check("layout: conventions.json layout limits apply", "read as one block: 0" in out and "M.flat" not in out)
os.remove(os.path.join(REPO, ".claude", "conventions.json"))

for name, ok in res:
    print(("PASS " if ok else "FAIL ") + name)
fails = [r for r in res if not r[1]]
print(f"{len(res) - len(fails)}/{len(res)}")
if os.environ.get("KEEP_T"):
    print(T)
else:
    shutil.rmtree(T, ignore_errors=True)
sys.exit(1 if fails else 0)
